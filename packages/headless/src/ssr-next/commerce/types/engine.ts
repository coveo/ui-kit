import type {Controller} from '../../../controllers/controller/headless-controller.js';
import type {EngineDefinition} from '../../common/types/engine.js';
import type {BuildConfig, SSRCommerceEngineOptions} from './build.js';
import type {SolutionType} from './controller-constants.js';
import type {ControllerDefinitionsMap} from './controller-definitions.js';
import type {CommerceStaticState} from './fetch-static-state.js';
import type {CommerceHydratedState} from './hydrate-static-state.js';

type ReservedControllerNames = 'context' | 'parameterManager' | 'cart';

type ValidateControllerNames<T extends ControllerDefinitionsMap<Controller>> = {
  [K in keyof T]: K extends ReservedControllerNames
    ? `ERROR: Controller name "${K & string}" is reserved and cannot be used. Reserved names are: context, parameterManager, cart. Please choose a different controller name.`
    : T[K];
};

/**
 * The options to create a Commerce engine definition in SSR.
 *
 * The context, the cart and the navigator context are per-request data: they are passed to
 * `fetchStaticState()` rather than to the engine definition.
 */
export type CommerceEngineDefinitionOptions<
  TControllers extends ControllerDefinitionsMap<Controller> = ControllerDefinitionsMap<Controller>,
> = SSRCommerceEngineOptions & {
  /**
   * The controllers to initialize with the commerce engine.
   */
  controllers?: ValidateControllerNames<TControllers>;
  /**
   * Not supported: the navigator context is per-request data. Pass `navigatorContext` to
   * `fetchStaticState()` instead.
   */
  navigatorContextProvider?: 'ERROR: navigatorContextProvider is removed. Pass navigatorContext to fetchStaticState() instead.';
};

/**
 * An engine definition for one kind of commerce page.
 *
 * @typeParam TControllers - The controllers passed to `defineCommerceEngine()`.
 * @typeParam TSolutionType - The kind of page the engine definition serves.
 */
export interface CommerceEngineDefinition<
  TControllers extends ControllerDefinitionsMap<Controller>,
  TSolutionType extends SolutionType,
> extends EngineDefinition<
  CommerceStaticState<TControllers, TSolutionType>,
  CommerceHydratedState<TControllers, TSolutionType>,
  BuildConfig<TControllers, TSolutionType>
> {
  /**
   * Executes the commerce request of the page (listing or search) and the requested recommendation
   * slots on the server side, and returns the static state.
   *
   * This method performs the initial commerce requests based on the solution type, captures the responses,
   * and returns a serializable state snapshot that can be transferred to the client for hydration.
   *
   * The returned static state includes controller states (facets, products, pagination, etc.)
   *
   * @param params - The page facts: the navigator context, the context, the cart, the search
   *                 parameters, the recommendation slots to request, the product being viewed and
   *                 the per-request access token
   * @returns A Promise that resolves to the static state containing controller states
   *
   * @example
   * ```typescript
   * // For a search page
   * const staticState = await searchEngineDefinition.fetchStaticState({
   *   navigatorContext: { ... },
   *   context: { ... },
   *   searchParams: { q: 'running shoes' }
   * });
   *
   * // For a product page with a seeded recommendation slot
   * const staticState = await standaloneEngineDefinition.fetchStaticState({
   *   navigatorContext: { ... },
   *   context: { ... },
   *   recommendations: ['viewedTogether'],
   *   productId: 'abc123'
   * });
   * ```
   */
  fetchStaticState: (
    params: BuildConfig<TControllers, TSolutionType>
  ) => Promise<CommerceStaticState<TControllers, TSolutionType>>;
  /**
   * Creates a commerce engine on the client side from the server-side static state.
   *
   * This method is used for client-side hydration in SSR scenarios. It takes the static state
   * generated by `fetchStaticState()` on the server and reconstructs a live commerce engine
   * with all controllers in the exact same state as they were on the server.
   *
   * The hydration process:
   * - Recreates the engine with the same configuration
   * - Restores all controller states from the static state
   * - Replays search/listing/recommendation actions to synchronize the state
   * - Returns live, interactive controllers ready for user interaction
   *
   * @param staticState - The static state returned by `fetchStaticState()`, passed as is.
   * @returns A Promise that resolves to the hydrated engine and interactive controllers
   *
   * @example
   * ```typescript
   * // In the browser, with `productList: defineProductList()` and `pagination: definePagination()`
   * // in the engine definition
   * const {engine, controllers} = await listingEngineDefinition.hydrateStaticState(staticState);
   *
   * // Controllers are now interactive
   * controllers.productList.state.products;
   * controllers.pagination.nextPage();
   * ```
   */
  hydrateStaticState: (
    staticState: CommerceStaticState<TControllers, TSolutionType>
  ) => Promise<CommerceHydratedState<TControllers, TSolutionType>>;
}

export type CommerceControllerDefinitionsMap = ControllerDefinitionsMap<Controller>;

type Definition<
  TControllerDefinitions extends CommerceControllerDefinitionsMap,
  TSolutionType extends SolutionType,
> = CommerceEngineDefinition<TControllerDefinitions, TSolutionType>;

type FetchStaticStateFunction<
  TControllerDefinitions extends CommerceControllerDefinitionsMap,
  TSolutionType extends SolutionType,
> = Definition<TControllerDefinitions, TSolutionType>['fetchStaticState'];

type HydrateStaticStateFunction<
  TControllerDefinitions extends CommerceControllerDefinitionsMap,
  TSolutionType extends SolutionType,
> = Definition<TControllerDefinitions, TSolutionType>['hydrateStaticState'];

export type FetchStaticStateParameters<
  TControllerDefinitions extends CommerceControllerDefinitionsMap,
  TSolutionType extends SolutionType,
> = Parameters<FetchStaticStateFunction<TControllerDefinitions, TSolutionType>>[0];

export type HydrateStaticStateParameters<
  TControllerDefinitions extends CommerceControllerDefinitionsMap,
  TSolutionType extends SolutionType,
> = Parameters<HydrateStaticStateFunction<TControllerDefinitions, TSolutionType>>[0];
